def _as_list(values):
    return [str(a) for a in (values.toArray() if hasattr(values, 'toArray') else values)]


def _take_replacements(argv):
    """argv içindeki tüm '--replace-image ad=yol' çiftlerini ayırır."""
    rest, found, i = [], {}, 0
    while i < len(argv):
        if argv[i] == '--replace-image' and i + 1 < len(argv):
            name, _, path = argv[i + 1].partition('=')
            found[name.strip().lower()] = Path(path)
            i += 2
        else:
            rest.append(argv[i])
            i += 1
    return rest, found


class _Session:
    """Python yolunu, günlük akışını ve yamaları hazırlar; çıkışta eski hâle getirir."""

    def __init__(self, root, native_dir, sink):
        self.root, self.native_dir, self.sink = str(root), str(native_dir) if native_dir else '', sink

    def __enter__(self):
        if self.root not in sys.path:
            sys.path.insert(0, self.root)
        os.chdir(self.root)
        self.out = _Sink(self.sink)
        self.saved = sys.stdout, sys.stderr, sys.argv
        sys.stdout = sys.stderr = self.out
        try:
            _patch(self.native_dir)
        except BaseException:
            self.__exit__()
            raise
        return self

    def __exit__(self, *exc):
        self.out.finish()
        sys.stdout, sys.stderr, sys.argv = self.saved
        return False


def run(root, native_dir, argv, sink):
    """Run the backend CLI with ``argv`` (list of str). Returns its exit code (0 ok, 130 cancelled)."""
    global _replacements
    try:
        with _Session(root, native_dir, sink):
            args, _replacements = _take_replacements(_as_list(argv))
            from flasher_builder import backend
            sys.argv = ['flasher-worker', '--repo', str(root)] + args
            return int(backend.main())
    except SystemExit as exit_:
        return int(exit_.code or 0) if isinstance(exit_.code, int) or exit_.code is None else 1
    except BaseException:
        traceback.print_exc()
        return 1


# ───────────────────────── OTA içindeki imajları listeleme / çıkarma ─────────────────────────

def _list_partitions(source, check=lambda: None):
    """payload.bin manifestini okuyup [(bölüm, boyut)] döndürür. Bağlantıda yalnızca birkaç yüz KB indirilir."""
    import io
    import struct
    import zipfile
    from urllib.parse import urlsplit
    from flasher_builder.backend import BuildError
    from flasher_builder.payload import fields, verify_full_payload
    from flasher_builder.remote_zip import RangeError, RangeReader

    class BufferedRange(RangeReader):
        """RangeReader yalnızca read() sunar; BufferedReader için readinto() eklenir (az sayıda HTTP isteği için)."""
        def readinto(self, buffer):
            data = self.read(len(buffer))
            buffer[:len(data)] = data
            return len(data)

    remote = urlsplit(source).scheme in ('http', 'https')
    try:
        stream = io.BufferedReader(BufferedRange(source, check), 1 << 20) if remote else open(source, 'rb')
        with stream, zipfile.ZipFile(stream) as archive:
            info = archive.getinfo('payload.bin')
            if remote and info.compress_type != zipfile.ZIP_STORED:
                raise BuildError('This OTA compresses payload.bin inside the ZIP and cannot be scanned remotely.')
            with archive.open(info) as payload:
                verify_full_payload(payload, info.file_size)       # tam (artımlı olmayan) OTA mı?
            with archive.open(info) as payload:
                header = payload.read(24)
                major, length, signature = struct.unpack('>QQI', header[4:])
                manifest = payload.read(length)
    except KeyError:
        raise BuildError('payload.bin not found: this is not a full A/B OTA ZIP.') from None
    except (RangeError, zipfile.BadZipFile, ValueError, struct.error) as error:
        raise BuildError(f'Could not read the OTA: {error}') from None
    parts = []
    for field, partition in fields(manifest):
        if field != 13:
            continue
        info_fields = dict(fields(partition))
        name = info_fields.get(1)
        size = dict(fields(info_fields.get(7, b''))).get(1, 0)
        if isinstance(name, bytes) and name:
            parts.append((name.decode('ascii', 'replace'), int(size)))
    return sorted(parts)


def _source_ok(backend, source):
    from urllib.parse import urlsplit
    if urlsplit(source).scheme not in ('http', 'https') and not Path(source).is_file():
        raise backend.BuildError('Enter an HTTP(S) OTA link or an existing OTA ZIP.')


def scan_images(root, native_dir, source, cancel_path, sink):
    """OTA'daki imajların adlarını ve boyutlarını '@@IMG ad boyut' satırları olarak yazar."""
    try:
        with _Session(root, native_dir, sink):
            from flasher_builder import backend
            try:
                source = str(source).strip()
                _source_ok(backend, source)
                worker = backend.Worker(str(cancel_path) if cancel_path else None)
                print('Scanning the OTA — only its manifest is downloaded.', flush=True)
                parts = _list_partitions(source, worker.check)
                for name, size in parts:
                    print(f'@@IMG {name} {size}', flush=True)
                print(f'{len(parts)} images found.', flush=True)
                return 0
            except backend.Cancelled as exc:
                print(str(exc), flush=True)
                return 130
            except (backend.BuildError, OSError, ValueError) as exc:
                print(f'ERROR: {exc}', flush=True)
                return 1
    except BaseException:
        traceback.print_exc()
        return 1


def extract_images(root, native_dir, source, names, out_dir, cancel_path, sink):
    """Seçilen imajları OTA'dan (bağlantıda yalnızca o bölümleri indirerek) out_dir/<ad>.img olarak çıkarır."""
    import shutil
    try:
        with _Session(root, native_dir, sink):
            from flasher_builder import backend, native_pipeline
            try:
                source = str(source).strip()
                _source_ok(backend, source)
                wanted = sorted({n.strip().lower() for n in _as_list(names) if n.strip()})
                bad = [n for n in wanted if n in BLOCKED_IMAGES]
                if not wanted or bad:
                    raise backend.BuildError('Select at least one image' + (f' ({", ".join(bad)} cannot be replaced).' if bad else '.'))
                worker = backend.Worker(str(cancel_path) if cancel_path else None)
                target_dir = Path(str(out_dir))
                target_dir.mkdir(parents=True, exist_ok=True)
                work = target_dir.parent / 'image-extract'
                shutil.rmtree(work, ignore_errors=True)
                print(f'Extracting {", ".join(wanted)} — only these partitions are downloaded.', flush=True)
                try:
                    directory = native_pipeline.extract(worker, Path(str(root)), source, work, tuple(wanted), strict=True)
                    missing = [n for n in wanted if not (directory / f'{n}.img').is_file()]
                    if missing:
                        raise backend.BuildError('Not found in this OTA: ' + ', '.join(missing))
                    for name in wanted:
                        image = directory / f'{name}.img'
                        if not image.stat().st_size:
                            raise backend.BuildError(f'{name}.img was extracted empty.')
                        destination = target_dir / f'{name}.img'
                        destination.unlink(missing_ok=True)
                        shutil.move(str(image), str(destination))
                        print(f'@@IMGDONE {name} {destination.stat().st_size}', flush=True)
                finally:
                    shutil.rmtree(work, ignore_errors=True)
                print('Images extracted.', flush=True)
                return 0
            except backend.Cancelled as exc:
                print(str(exc), flush=True)
                return 130
            except (backend.BuildError, OSError, ValueError) as exc:
                print(f'ERROR: {exc}', flush=True)
                return 1
    except BaseException:
        traceback.print_exc()
        return 1
